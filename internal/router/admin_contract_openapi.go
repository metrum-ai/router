package router

// OpenAPI 3.1 generation for the /admin/v1 contract (ACP-012).
//
// The document is generated from the typed route registry, not hand-written:
// the registry already carries the authorization object/action, the concurrency
// and idempotency semantics, the pagination and filter set, the deprecation
// window and the request/response prototypes, so the published contract cannot
// drift from the mounted routes without a registry change.
//
// Why a reflection generator instead of a third-party library: the project
// already depends on enough crypto and network surface, OpenAPI 3.1 is JSON
// Schema 2020-12 (so Go type → schema is direct: no 3.0 nullable shims), and
// byte-determinism is what makes the CI drift check meaningful. Adding
// github.com/getkin/kin-openapi would pull ~20 modules and still require custom
// schema work for the 3.1 dialect.
//
// Determinism rules: schemas are named after their Go type and serialised from
// a map (encoding/json sorts map keys), properties keep declaration order,
// operations are ordered by (path, method), and no build, timestamp or host
// value appears anywhere in the document.

import (
	"encoding/json"
	"fmt"
	"reflect"
	"sort"
	"strings"
	"time"
)

// AdminOpenAPIVersion is the contract version published in the document.
const AdminOpenAPIVersion = "1.0.0"

// AdminOpenAPIPath is where the generated document lives in the repository.
// The drift test compares the regenerated bytes with this file.
const AdminOpenAPIPath = "docs/specs/admin-v1.openapi.json"

const adminOpenAPIDescription = "Machine-to-machine admin control plane of the Metrum AI Router. " +
	"Every operation is authorized by the Casbin authorizer in one decision per operation, rejects Basic, " +
	"cookie and browser credentials, and answers errors as RFC 9457 `application/problem+json`. " +
	"Concurrency: operations marked with `x-admin-concurrency: revision` require `If-Match` (428 when missing, " +
	"412 when stale) against the strong ETag `\"rev-<configuration revision>\"`; collections return `Link` " +
	"`rel=\"next\"` cursor pagination instead of an ETag. Idempotency: operations marked with " +
	"`x-admin-idempotency` accept `Idempotency-Key` scoped to principal, domain and operation, retained 24 h and " +
	"persisted, so a retry replays the original response and a different body on the same key answers 409. " +
	"Response schemas are exact where a handler returns a typed value; handlers that still return an untyped " +
	"object are documented as an open object whose description lists its members."

// GenerateAdminOpenAPI renders the OpenAPI 3.1 document for the given
// operations.
func GenerateAdminOpenAPI(operations []Operation) ([]byte, error) {
	generator := &adminOpenAPIGenerator{
		schemas: map[string]any{},
		seen:    map[reflect.Type]bool{},
	}
	document := map[string]any{
		"openapi": "3.1.0",
		"info": map[string]any{
			"title":       "Metrum AI Router admin API",
			"version":     AdminOpenAPIVersion,
			"description": adminOpenAPIDescription,
			"license":     map[string]any{"name": "Apache-2.0", "identifier": "Apache-2.0"},
		},
		"servers":  []any{map[string]any{"url": "/", "description": "Admin listener"}},
		"security": []any{map[string]any{"adminBearerAuth": []any{}}, map[string]any{"adminMutualTLS": []any{}}},
	}

	paths := map[string]any{}
	ordered := append([]Operation(nil), operations...)
	sort.Slice(ordered, func(i, j int) bool {
		if ordered[i].Path != ordered[j].Path {
			return ordered[i].Path < ordered[j].Path
		}
		return ordered[i].Method < ordered[j].Method
	})
	for _, op := range ordered {
		item, err := generator.operation(op)
		if err != nil {
			return nil, fmt.Errorf("operation %s: %w", op.ID, err)
		}
		pathItem, _ := paths[op.Path].(map[string]any)
		if pathItem == nil {
			pathItem = map[string]any{}
			paths[op.Path] = pathItem
		}
		pathItem[strings.ToLower(op.Method)] = item
	}

	document["paths"] = paths
	document["components"] = map[string]any{
		"schemas": generator.schemas,
		"securitySchemes": map[string]any{
			"adminBearerAuth": map[string]any{
				"type": "http", "scheme": "bearer",
				"description": "Admin API key (`rtr_admin_...`) or an OAuth 2.0 client-credentials access token. Basic and cookie credentials are rejected.",
			},
			"adminMutualTLS": map[string]any{
				"type":        "mutualTLS",
				"description": "mTLS client identity verified against the configured client CA snapshot; the certificate supplies the principal and any sender constraint.",
			},
		},
		"responses": map[string]any{
			"Problem": map[string]any{
				"description": "RFC 9457 problem document. `code` is the stable machine-readable value; `type` is its URN.",
				"content": map[string]any{
					"application/problem+json": map[string]any{"schema": map[string]any{"$ref": "#/components/schemas/AdminProblem"}},
				},
			},
		},
	}

	// The problem schema is part of the contract whether or not an operation
	// referenced it directly.
	if _, err := generator.schemaFor(reflect.TypeOf(AdminProblem{})); err != nil {
		return nil, err
	}
	document["components"].(map[string]any)["schemas"] = generator.schemas

	encoded, err := json.MarshalIndent(document, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(encoded, '\n'), nil
}

type adminOpenAPIGenerator struct {
	schemas map[string]any
	seen    map[reflect.Type]bool
}

func (g *adminOpenAPIGenerator) operation(op Operation) (map[string]any, error) {
	item := map[string]any{
		"operationId":         op.ID,
		"summary":             op.Summary,
		"tags":                []any{adminOpenAPITag(op)},
		"x-admin-object":      op.Object,
		"x-admin-action":      op.Action,
		"x-admin-domain":      string(op.Domain),
		"x-admin-concurrency": string(op.Concurrency),
		"x-admin-idempotency": string(op.Idempotency),
	}
	if op.Description != "" {
		item["description"] = op.Description
	}
	if op.NoSideEffect {
		item["x-admin-side-effects"] = "none"
	}
	if op.Deprecated != nil {
		item["deprecated"] = true
		item["x-admin-deprecation"] = map[string]any{
			"since":  op.Deprecated.Since.UTC().Format(time.RFC3339),
			"sunset": op.Deprecated.Sunset.UTC().Format(time.RFC3339),
		}
		if op.Deprecated.Note != "" {
			item["x-admin-deprecation-replacement"] = op.Deprecated.Note
		}
	}
	if len(op.ExtraChecks) > 0 {
		checks := make([]any, 0, len(op.ExtraChecks))
		for _, check := range op.ExtraChecks {
			entry := map[string]any{"object": check.Object, "action": check.Action}
			if check.When == AdminCheckBodyForce {
				// Conditional: today's handlers ask for force only when the request
				// body sets force: true, so a plain write does not need the grant.
				entry["when"] = string(AdminCheckBodyForce)
				entry["description"] = "Required only when the request body sets force: true."
			} else {
				entry["when"] = "always"
			}
			checks = append(checks, entry)
		}
		item["x-admin-extra-checks"] = checks
	}

	parameters := []any{}
	for _, name := range adminPathParameterNames(op.Path) {
		parameters = append(parameters, map[string]any{
			"name": name, "in": "path", "required": true,
			"schema": map[string]any{"type": "string"},
		})
	}
	for _, param := range op.Query {
		parameter := map[string]any{
			"name": param.Name, "in": "query",
			"schema": map[string]any{"type": "string"},
		}
		if param.Description != "" {
			parameter["description"] = param.Description
		}
		if param.Required {
			parameter["required"] = true
		}
		if len(param.Enum) > 0 {
			values := make([]any, 0, len(param.Enum))
			for _, value := range param.Enum {
				values = append(values, value)
			}
			parameter["schema"] = map[string]any{"type": "string", "enum": values}
		}
		parameters = append(parameters, parameter)
	}
	if op.Pagination != nil {
		parameters = append(parameters,
			map[string]any{"name": "limit", "in": "query", "description": fmt.Sprintf("Page size. Default %d, maximum %d.", AdminV1DefaultLimit, AdminV1MaxLimit), "schema": map[string]any{"type": "integer", "minimum": 1, "maximum": AdminV1MaxLimit, "default": AdminV1DefaultLimit}},
			map[string]any{"name": "cursor", "in": "query", "description": "Opaque cursor from the previous page's Link header. Bound to this operation's filter and sort set.", "schema": map[string]any{"type": "string"}},
			map[string]any{"name": "sort", "in": "query", "schema": map[string]any{"type": "string", "enum": adminStringsToAny(op.Pagination.Sorts), "default": op.Pagination.DefaultSort}},
			map[string]any{"name": "direction", "in": "query", "schema": map[string]any{"type": "string", "enum": []any{"asc", "desc"}, "default": "asc"}},
		)
	}
	if op.RequiredPrecondition() {
		parameters = append(parameters, map[string]any{
			"name": "If-Match", "in": "header", "required": true,
			"description": "Strong ETag of the resource's current state. Required: 428 when missing, 412 when stale.",
			"schema":      map[string]any{"type": "string"},
		})
	}
	if op.Idempotency != AdminIdempotencyNone {
		parameters = append(parameters, map[string]any{
			"name": "Idempotency-Key", "in": "header",
			"description": "Replay-safe request key, scoped to principal, domain and operation, retained 24 h.",
			"schema":      map[string]any{"type": "string", "maxLength": 128},
		})
	}
	if len(parameters) > 0 {
		item["parameters"] = parameters
	}

	if op.Request != nil {
		schema, err := g.schemaFor(reflect.TypeOf(op.Request))
		if err != nil {
			return nil, err
		}
		item["requestBody"] = map[string]any{
			"required": op.Method != "DELETE",
			"content":  map[string]any{"application/json": map[string]any{"schema": schema}},
		}
	}

	responses := map[string]any{}
	success := op.SuccessStatus
	if success == 0 {
		success = 200
	}
	if op.Response != nil {
		schema, contentType, err := g.responseSchema(op.Response)
		if err != nil {
			return nil, err
		}
		responses[fmt.Sprintf("%d", success)] = map[string]any{
			"description": "Success",
			"content":     map[string]any{contentType: map[string]any{"schema": schema}},
		}
	} else {
		responses[fmt.Sprintf("%d", success)] = map[string]any{"description": "Success"}
	}
	for _, status := range adminOperationErrorStatuses(op) {
		responses[fmt.Sprintf("%d", status)] = map[string]any{"$ref": "#/components/responses/Problem"}
	}
	item["responses"] = responses
	return item, nil
}

func (g *adminOpenAPIGenerator) responseSchema(prototype any) (any, string, error) {
	switch typed := prototype.(type) {
	case adminOpenObject:
		description := "Unspecified object"
		if len(typed.Members) > 0 {
			description = "Open object. Documented members: " + strings.Join(typed.Members, ", ") + "."
		}
		return map[string]any{"type": "object", "additionalProperties": true, "description": description}, "application/json", nil
	case adminBinaryBody:
		mediaType := typed.MediaType
		if mediaType == "" {
			mediaType = "application/octet-stream"
		}
		return map[string]any{"type": "string", "format": "binary"}, mediaType, nil
	case adminTextBody:
		mediaType := typed.MediaType
		if mediaType == "" {
			mediaType = "text/plain"
		}
		return map[string]any{"type": "string"}, mediaType, nil
	}
	schema, err := g.schemaFor(reflect.TypeOf(prototype))
	if err != nil {
		return nil, "", err
	}
	return schema, "application/json", nil
}

// schemaFor returns the JSON Schema of one Go type, registering named structs
// in components.schemas.
func (g *adminOpenAPIGenerator) schemaFor(t reflect.Type) (any, error) {
	if t == nil {
		return map[string]any{}, nil
	}
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	if t == reflect.TypeOf(time.Time{}) {
		return map[string]any{"type": "string", "format": "date-time"}, nil
	}
	switch t.Kind() {
	case reflect.String:
		return map[string]any{"type": "string"}, nil
	case reflect.Bool:
		return map[string]any{"type": "boolean"}, nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32:
		// JSON numbers are open in 3.1; keep the integer type explicit.
		return map[string]any{"type": "integer"}, nil
	case reflect.Int64:
		return map[string]any{"type": "integer", "format": "int64"}, nil
	case reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		return map[string]any{"type": "integer", "minimum": 0}, nil
	case reflect.Float32, reflect.Float64:
		return map[string]any{"type": "number"}, nil
	case reflect.Slice, reflect.Array:
		if t.Elem().Kind() == reflect.Uint8 {
			return map[string]any{"type": "string", "format": "byte"}, nil
		}
		items, err := g.schemaFor(t.Elem())
		if err != nil {
			return nil, err
		}
		return map[string]any{"type": "array", "items": items}, nil
	case reflect.Map:
		valueSchema, err := g.schemaFor(t.Elem())
		if err != nil {
			return nil, err
		}
		return map[string]any{"type": "object", "additionalProperties": valueSchema}, nil
	case reflect.Interface:
		return map[string]any{"type": "object", "additionalProperties": true}, nil
	case reflect.Struct:
		if name := t.Name(); name != "" {
			if _, exists := g.schemas[name]; !exists {
				// Reserve the name before recursing so a self-referencing type
				// resolves to its own $ref instead of looping.
				g.schemas[name] = map[string]any{"type": "object", "additionalProperties": true}
				body, err := g.structSchema(t)
				if err != nil {
					return nil, err
				}
				g.schemas[name] = body
			}
			return map[string]any{"$ref": "#/components/schemas/" + name}, nil
		}
		return g.structSchema(t)
	default:
		return map[string]any{}, nil
	}
}

func (g *adminOpenAPIGenerator) structSchema(t reflect.Type) (any, error) {
	properties := map[string]any{}
	required := []any{}
	for i := 0; i < t.NumField(); i++ {
		field := t.Field(i)
		if field.PkgPath != "" {
			continue
		}
		name, omitEmpty, skip := adminJSONFieldName(field)
		if skip {
			continue
		}
		fieldSchema, err := g.schemaFor(field.Type)
		if err != nil {
			return nil, err
		}
		if description := adminFieldDescription(field); description != "" {
			if object, ok := fieldSchema.(map[string]any); ok {
				object["description"] = description
			}
		}
		properties[name] = fieldSchema
		if !omitEmpty {
			required = append(required, name)
		}
	}
	schema := map[string]any{"type": "object", "properties": properties}
	if len(required) > 0 {
		schema["required"] = required
	}
	return schema, nil
}

func adminJSONFieldName(field reflect.StructField) (name string, omitEmpty, skip bool) {
	tag := field.Tag.Get("json")
	if tag == "-" {
		return "", false, true
	}
	parts := strings.Split(tag, ",")
	name = parts[0]
	if name == "" {
		name = field.Name
	}
	for _, opt := range parts[1:] {
		if opt == "omitempty" {
			omitEmpty = true
		}
	}
	return name, omitEmpty, false
}

func adminFieldDescription(field reflect.StructField) string {
	if openapiTag := field.Tag.Get("openapi"); openapiTag != "" {
		if description, found := strings.CutPrefix(openapiTag, "description="); found {
			return description
		}
	}
	return ""
}

func adminPathParameterNames(path string) []string {
	var names []string
	for _, segment := range strings.Split(path, "/") {
		if strings.HasPrefix(segment, "{") && strings.HasSuffix(segment, "}") {
			names = append(names, strings.TrimSuffix(strings.TrimPrefix(segment, "{"), "}"))
		}
	}
	return names
}

func adminOpenAPITag(op Operation) string {
	if op.Adapter == "reports" {
		return "reports"
	}
	switch {
	case strings.HasPrefix(op.Path, "/admin/v1/config"),
		strings.HasPrefix(op.Path, "/admin/v1/callers"):
		return "configuration"
	case strings.HasPrefix(op.Path, "/admin/v1/training"):
		return "training"
	case strings.HasPrefix(op.Path, "/admin/v1/content-captures"):
		return "content-captures"
	case strings.HasPrefix(op.Path, "/admin/v1/metrics"):
		return "metrics"
	}
	return "admin"
}

// adminOperationErrorStatuses is the documented error set: the contract-wide
// codes every operation can answer plus the operation's own route-specific
// ones.
func adminOperationErrorStatuses(op Operation) []int {
	statuses := map[int]bool{400: true, 401: true, 403: true, 429: true, 500: true, 503: true}
	for _, status := range op.Errors {
		if status >= 400 {
			statuses[status] = true
		}
	}
	if op.RequiredPrecondition() {
		statuses[412] = true
		statuses[428] = true
	}
	if op.Idempotency != AdminIdempotencyNone {
		statuses[409] = true
	}
	out := make([]int, 0, len(statuses))
	for status := range statuses {
		out = append(out, status)
	}
	sort.Ints(out)
	return out
}

func adminStringsToAny(values []string) []any {
	out := make([]any, 0, len(values))
	for _, value := range values {
		out = append(out, value)
	}
	return out
}
