"""Validate, render and reconcile the tool-call compatibility matrix.

`tests/tool_compat/matrix.json` is the single source of truth for the
client x API-surface x path cells that are proven, tracked as failing, or
explicitly not covered. The published page
`docs-site/docs/evaluation/tool-call-matrix.md` is generated from it, so a cell
cannot be claimed on the page without existing in the data, a cell cannot exist
without stating its tier, evidence and (for failures) its issue, and a client
surface cannot silently omit a caller path.

Commands:

    --check                  validate the matrix and the generated page
    --check --allow-untriaged  same, but allow recorded live failures without an issue
    --write                  regenerate the page from the matrix
    --ingest REPORT          record a live-run report into the matrix (stdout)
    --ingest REPORT --write  record it into tests/tool_compat/matrix.json
    --compare BASELINE       fail when a cell regressed against a baseline matrix

Nothing here calls a provider, a network endpoint or the GitHub API.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MATRIX_PATH = ROOT / "tests" / "tool_compat" / "matrix.json"
PAGE_PATH = ROOT / "docs-site" / "docs" / "evaluation" / "tool-call-matrix.md"
PAGE_ROUTE = "docs-site/docs/evaluation/tool-call-matrix.md"
COMPAT_MOCK = ROOT / "scripts" / "compat_mock.py"
BLOB = "https://github.com/metrum-ai/router/blob/main/"

SURFACES = {"openai-chat", "openai-responses", "anthropic-messages"}
PATHS = {
    "same-dialect": None,
    "chat_to_responses": ("openai-chat", "openai-responses"),
    "chat_to_messages": ("openai-chat", "anthropic-messages"),
    "responses_to_chat": ("openai-responses", "openai-chat"),
    "messages_to_chat": ("anthropic-messages", "openai-chat"),
}
FEATURES = {
    "streaming",
    "tool_call",
    "parallel_calls",
    "strict_json",
    "thinking",
    "cache_control",
    "forced_tool_choice",
    "provider_hosted_tools",
    "media_in_tool_result",
}
TIERS = {"mock", "unit", "live", "unsupported", "not-covered"}
STATUSES = {"pass", "fail", "not-covered", "unsupported", "not-run"}
COST_SOURCES = {"usage_rows", "provider_invoiced", "estimate", "not_recorded"}
EVIDENCE_KINDS = {"doc", "issue", "run", "ci", "code"}
REPORT_RUNNERS = {"agent-tool-compat-live", "parallel-tool-live", "compat-live", "manual"}
SDK_TESTERS = {"openai-sdk", "anthropic-sdk"}

GENERATED_NOTICE = (
    "<!-- Generated by scripts/tool_compat_matrix.py from tests/tool_compat/matrix.json. "
    "Edit the matrix, not this page; run `python3 scripts/tool_compat_matrix.py --write`. -->"
)


class MatrixError(ValueError):
    pass


def load(path: Path) -> dict:
    with Path(path).open(encoding="utf-8") as handle:
        return json.load(handle)


def slugify(heading: str) -> str:
    text = heading.strip().lower()
    text = re.sub(r"[`*_]", "", text)
    text = re.sub(r"[^a-z0-9 -]", "", text)
    return text.replace(" ", "-")


def headings(path: Path) -> set[str]:
    found = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        match = re.match(r"^(#{1,6})\s+(.*)$", line)
        if match:
            found.add(slugify(match.group(2)))
    return found


def compat_mock_suites() -> set[str]:
    """Suite names the pinned SDK testers actually run, read from the pin file."""
    text = COMPAT_MOCK.read_text(encoding="utf-8")
    match = re.search(r"TESTERS = \{(.*?)\n\}", text, re.S)
    if not match:
        raise MatrixError("cannot read TESTERS from scripts/compat_mock.py")
    suites: set[str] = set()
    for entry in re.findall(r"'[^']+':\s*\('[0-9a-f]+',\s*'([^']+)'\)", match.group(1), re.S):
        suites.update(part.strip() for part in entry.split(",") if part.strip())
    if not suites:
        raise MatrixError("no tester suites found in scripts/compat_mock.py")
    return suites


def validate_doc_ref(cell_id: str, ref: str) -> list[str]:
    path_text, _, anchor = ref.partition("#")
    path = ROOT / path_text
    if not path.exists():
        return [f"{cell_id}: doc ref does not exist: {path_text}"]
    if anchor and slugify(anchor) not in headings(path):
        return [f"{cell_id}: doc ref anchor not found: {ref}"]
    return []


def validate_evidence(cell_id: str, evidence: object) -> list[str]:
    if not isinstance(evidence, dict):
        return [f"{cell_id}: evidence must be an object"]
    kind = evidence.get("kind")
    ref = evidence.get("ref")
    if kind not in EVIDENCE_KINDS:
        return [f"{cell_id}: evidence kind must be one of {sorted(EVIDENCE_KINDS)}"]
    if not isinstance(ref, str) or not ref:
        return [f"{cell_id}: evidence ref must be a non-empty string"]
    if kind == "doc":
        return validate_doc_ref(cell_id, ref)
    if kind == "issue":
        if not re.fullmatch(r"https://github\.com/metrum-ai/router/issues/[1-9][0-9]*", ref):
            return [f"{cell_id}: issue evidence must be a metrum-ai/router issue URL"]
        return []
    if kind == "run":
        if not re.fullmatch(r"https://github\.com/metrum-ai/router/actions/runs/[1-9][0-9]*", ref):
            return [f"{cell_id}: run evidence must be an actions run URL"]
        return []
    if not (ROOT / ref).exists():
        return [f"{cell_id}: {kind} evidence file does not exist: {ref}"]
    return []


def validate_cost(cell_id: str, require: bool, cost: object) -> list[str]:
    if cost is None:
        return [f"{cell_id}: live evidence needs a cost object"] if require else []
    if not isinstance(cost, dict):
        return [f"{cell_id}: cost must be an object"]
    errors: list[str] = []
    source = cost.get("source")
    usd = cost.get("usd")
    if source not in COST_SOURCES:
        errors.append(f"{cell_id}: cost.source must be one of {sorted(COST_SOURCES)}")
    if usd is not None and (isinstance(usd, bool) or not isinstance(usd, (int, float)) or usd < 0):
        errors.append(f"{cell_id}: cost.usd must be a non-negative number or null")
    if usd is None and source not in {"provider_invoiced", "not_recorded"}:
        errors.append(f"{cell_id}: cost.usd may be null only for provider_invoiced or not_recorded")
    if source == "estimate" and "invoice pending" not in (cost.get("note") or ""):
        errors.append(f"{cell_id}: estimate cost must be labelled 'invoice pending'")
    if cost.get("scope") not in {"cell", "run"}:
        errors.append(f"{cell_id}: cost.scope must be cell or run")
    return errors


def validate_live_block(cell_id: str, live: object) -> list[str]:
    if not isinstance(live, dict):
        return [f"{cell_id}: live must be an object"]
    errors: list[str] = []
    if not isinstance(live.get("date"), str) or not re.fullmatch(r"\d{4}-\d{2}-\d{2}", live["date"]):
        errors.append(f"{cell_id}: live.date must be YYYY-MM-DD")
    if not isinstance(live.get("commit"), str) or not re.fullmatch(r"[0-9a-f]{7,40}", live["commit"]):
        errors.append(f"{cell_id}: live.commit must be a hex commit")
    if live.get("runner") not in REPORT_RUNNERS:
        errors.append(f"{cell_id}: live.runner must be one of {sorted(REPORT_RUNNERS)}")
    errors.extend(validate_cost(cell_id, True, live.get("cost")))
    if live.get("triage_required") not in (None, False, True):
        errors.append(f"{cell_id}: live.triage_required must be boolean")
    return errors


def validate_status_tier(cell_id: str, tier: object, status: object) -> list[str]:
    errors: list[str] = []
    if tier not in TIERS:
        errors.append(f"{cell_id}: unknown tier {tier!r}")
    if status not in STATUSES:
        errors.append(f"{cell_id}: unknown status {status!r}")
    if tier == "not-covered" and status != "not-covered":
        errors.append(f"{cell_id}: tier not-covered requires status not-covered")
    if status == "not-covered" and tier != "not-covered":
        errors.append(f"{cell_id}: status not-covered requires tier not-covered")
    if tier == "unsupported" and status != "unsupported":
        errors.append(f"{cell_id}: tier unsupported requires status unsupported")
    if status == "unsupported" and tier != "unsupported":
        errors.append(f"{cell_id}: status unsupported requires tier unsupported")
    return errors


def validate_cell(cell: dict, client_ids: list[str], sdk_suites: set[str]) -> list[str]:
    cell_id = cell.get("id", "<no id>")
    errors: list[str] = []
    if cell.get("client") not in client_ids:
        errors.append(f"{cell_id}: unknown client {cell.get('client')!r}")
    path = cell.get("path")
    surface = cell.get("surface")
    upstream = cell.get("upstream")
    if path not in PATHS:
        errors.append(f"{cell_id}: unknown path {path!r}")
    if surface not in SURFACES or upstream not in SURFACES:
        errors.append(f"{cell_id}: surface/upstream must be one of {sorted(SURFACES)}")
    elif path in PATHS:
        if path == "same-dialect" and surface != upstream:
            errors.append(f"{cell_id}: same-dialect cell has surface {surface} and upstream {upstream}")
        if path != "same-dialect" and (surface, upstream) != PATHS[path]:
            errors.append(f"{cell_id}: path {path} expects {PATHS[path]}, got {(surface, upstream)}")
    features = cell.get("features") or []
    if not features or not set(features) <= FEATURES:
        errors.append(f"{cell_id}: unknown or empty features {features!r}")
    errors.extend(validate_status_tier(cell_id, cell.get("tier"), cell.get("status")))
    depths = cell.get("depths")
    if depths is not None and (
        not isinstance(depths, list)
        or not depths
        or not all(isinstance(depth, int) and not isinstance(depth, bool) and 0 <= depth <= 9 for depth in depths)
    ):
        errors.append(f"{cell_id}: depths must be a non-empty list of ints 0..9")
    errors.extend(validate_evidence(cell_id, cell.get("evidence")))
    if cell.get("status") == "not-covered" and not str(cell.get("reason") or "").strip():
        errors.append(f"{cell_id}: not-covered cell needs a reason")
    if cell.get("status") == "fail":
        if not isinstance(cell.get("issue"), int) or isinstance(cell.get("issue"), bool):
            untriaged = bool((cell.get("live") or {}).get("triage_required"))
            if not untriaged:
                errors.append(f"{cell_id}: failing cell needs a triage issue")
    if cell.get("issue") is not None and not isinstance(cell.get("issue"), int):
        errors.append(f"{cell_id}: issue must be an integer number")
    if cell.get("status") == "unsupported":
        doc = cell.get("doc")
        if not doc:
            errors.append(f"{cell_id}: unsupported cell must cite the doc line that declares it")
        else:
            errors.extend(validate_doc_ref(cell_id, doc))
    suite = cell.get("suite")
    if suite is not None:
        if cell.get("client") not in SDK_TESTERS:
            errors.append(f"{cell_id}: suite is only valid for the pinned SDK testers")
        elif suite not in sdk_suites:
            errors.append(f"{cell_id}: suite {suite!r} is not in scripts/compat_mock.py TESTERS")
    errors.extend(
        validate_cost(cell_id, cell.get("tier") == "live" and cell.get("live") is None, cell.get("cost"))
    )
    if cell.get("live") is not None:
        errors.extend(validate_live_block(cell_id, cell["live"]))
    elif cell.get("tier") == "live":
        errors.append(f"{cell_id}: live tier needs a live block with date, commit, runner and cost")
    return errors


def validate(matrix: dict, allow_untriaged: bool = False) -> list[str]:
    errors: list[str] = []
    if matrix.get("schema_version") != 1:
        errors.append("schema_version must be 1")
    clients = matrix.get("clients") or []
    if not isinstance(clients, list) or not clients:
        errors.append("clients must be a non-empty list")
        clients = []
    client_ids: list[str] = []
    for client in clients:
        name = client.get("id")
        if not isinstance(name, str) or not name:
            errors.append(f"client without id: {client!r}")
            continue
        if name in client_ids:
            errors.append(f"duplicate client id {name}")
        client_ids.append(name)
        surfaces = client.get("surfaces") or []
        if not surfaces or not set(surfaces) <= SURFACES:
            errors.append(f"client {name} has unknown or empty surfaces {surfaces!r}")
        if not client.get("name") or not client.get("version") or not client.get("pin"):
            errors.append(f"client {name} needs name, version and pin")
        elif not (ROOT / client["pin"]).exists():
            errors.append(f"client {name} pin file does not exist: {client['pin']}")

    sdk_suites = compat_mock_suites()
    cells = matrix.get("cells") or []
    if not isinstance(cells, list) or not cells:
        errors.append("cells must be a non-empty list")
        cells = []
    seen: set[str] = set()
    for cell in cells:
        cell_id = cell.get("id")
        if not isinstance(cell_id, str) or not cell_id:
            errors.append(f"cell without id: {cell!r}")
            continue
        if cell_id in seen:
            errors.append(f"duplicate cell id {cell_id}")
        seen.add(cell_id)
        errors.extend(validate_cell(cell, client_ids, sdk_suites))
    if not allow_untriaged:
        for cell in cells:
            if (cell.get("live") or {}).get("triage_required"):
                errors.append(
                    f"{cell.get('id')}: live failure recorded without a triage issue;"
                    " open an issue and set the cell's issue number"
                )
    errors.extend(required_combinations(clients, cells))
    errors.extend(validate_router_cells(matrix))
    for client in matrix.get("not_covered_clients") or []:
        if not client.get("id") or not client.get("reason"):
            errors.append(f"not_covered_clients entry needs id and reason: {client!r}")
        if not client.get("name") or not client.get("version"):
            errors.append(f"not_covered_clients {client.get('id')} needs name and version")
    limits = matrix.get("limits") or []
    if not limits:
        errors.append("limits must be a non-empty list")
    for limit in limits:
        if not isinstance(limit, str) or not limit.strip():
            errors.append("limits entries must be non-empty strings")
    return errors


def required_combinations(clients: list[dict], cells: list[dict]) -> list[str]:
    """Every declared client surface must state a result for every caller path."""
    errors: list[str] = []
    present = {
        (cell.get("client"), cell.get("surface"), cell.get("path"))
        for cell in cells
    }
    for client in clients:
        for surface in client.get("surfaces") or []:
            for path, pair in PATHS.items():
                if path != "same-dialect" and pair[0] != surface:
                    continue
                if (client.get("id"), surface, path) not in present:
                    errors.append(
                        f"client {client.get('id')} surface {surface} has no cell for path {path}"
                        " (add a result or an explicit not-covered cell)"
                    )
    return errors


def validate_router_cells(matrix: dict) -> list[str]:
    errors: list[str] = []
    seen: set[str] = set()
    for cell in matrix.get("router_cells") or []:
        cell_id = cell.get("id")
        if not isinstance(cell_id, str) or not cell_id:
            errors.append(f"router cell without id: {cell!r}")
            continue
        if cell_id in seen:
            errors.append(f"duplicate router cell id {cell_id}")
        seen.add(cell_id)
        if not cell.get("area"):
            errors.append(f"{cell_id}: router cell needs an area")
        features = cell.get("features") or []
        if not features or not set(features) <= FEATURES:
            errors.append(f"{cell_id}: unknown or empty features {features!r}")
        errors.extend(validate_status_tier(cell_id, cell.get("tier"), cell.get("status")))
        if cell.get("status") == "fail" and not isinstance(cell.get("issue"), int):
            errors.append(f"{cell_id}: failing router cell needs a triage issue")
        if cell.get("doc"):
            errors.extend(validate_doc_ref(cell_id, cell["doc"]))
        if cell.get("status") == "unsupported" and not cell.get("doc"):
            errors.append(f"{cell_id}: unsupported router cell must cite a doc")
        errors.extend(validate_evidence(cell_id, cell.get("evidence")))
        errors.extend(validate_cost(cell_id, cell.get("tier") == "live", cell.get("cost")))
    return errors


def result_label(cell: dict) -> str:
    status = cell.get("status")
    if status == "not-covered":
        return "not covered"
    if status == "unsupported":
        return "unsupported"
    if status == "not-run":
        return "not run"
    return f"{status} ({cell.get('tier')})"


def usd_text(cost: dict) -> str:
    if cost.get("usd") is None:
        return "not recorded"
    return f"${cost['usd']:.8f}".rstrip("0").rstrip(".")


def doc_link(ref: str, label: str | None = None) -> str:
    return f"[{label or ref}]({BLOB}{ref})"


def evidence_text(cell: dict) -> str:
    evidence = cell["evidence"]
    ref = evidence["ref"]
    if evidence["kind"] == "doc":
        anchor = ref.split("#")[-1]
        label = anchor.replace("-", " ") if "#" in ref else Path(ref).name
        return doc_link(ref, label)
    if evidence["kind"] == "issue":
        return f"[issue {ref.rsplit('/', 1)[-1]}]({ref})"
    if evidence["kind"] == "run":
        return f"[run {ref.rsplit('/', 1)[-1]}]({ref})"
    return f"`{ref}`"


def render(matrix: dict) -> str:
    clients = {client["id"]: client for client in matrix["clients"]}
    cells = matrix["cells"]
    lines: list[str] = []
    add = lines.append

    add("---")
    add("title: Tool-call compatibility matrix")
    add("doc_type: explanation")
    add("---")
    add("")
    add("<!-- Copyright 2026 Metrum AI -->")
    add("<!-- SPDX-License-Identifier: Apache-2.0 -->")
    add("")
    add(GENERATED_NOTICE)
    add("")
    add("# Tool-call compatibility matrix")
    add("")
    add(
        "Every cell states what is proven, for which client version, on which caller-to-upstream path,"
        " with the evidence that proves it. A combination that is not proven is listed as not covered"
        " with its reason, never omitted. Last matrix update: " + str(matrix["updated"]) + "."
    )
    add("")
    add(
        "A `mock` cell is a deterministic scripted upstream; a `unit` cell is a local conversion check"
        " with no endpoint call; a `live` cell ran against a real provider and carries its date, commit,"
        " cost and cost source. Mock and live evidence are never merged into one result. The underlying"
        " per-suite evidence lives in [bounded tool-call proof](tool-call-proof) and"
        " [live API compatibility](api-compatibility-live)."
    )
    add("")
    add("## Clients")
    add("")
    add("| Client | Version | Pinned by | Caller surfaces |")
    add("| --- | --- | --- | --- |")
    for client in matrix["clients"]:
        add(
            f"| {client['name']} | {client['version']} | `{client['pin']}` |"
            f" {', '.join(client['surfaces'])} |"
        )
    add("")
    if matrix.get("not_covered_clients"):
        add("Clients with no cell yet, and why:")
        add("")
        add("| Client | Version | Why no cell |")
        add("| --- | --- | --- |")
        for client in matrix["not_covered_clients"]:
            add(f"| {client['name']} | {client['version']} | {client['reason']} |")
        add("")

    add("## Coverage by client and path")
    add("")
    path_order = list(PATHS)
    add("| Client | " + " | ".join(path_order) + " |")
    add("| --- | " + " | ".join("---" for _ in path_order) + " |")
    for client in matrix["clients"]:
        row = [f"{client['name']} {client['version']}"]
        for path in path_order:
            matching = [
                cell
                for cell in cells
                if cell["client"] == client["id"] and cell["path"] == path
            ]
            if not matching:
                row.append("—")
                continue
            # MDX treats a bare <br> as an unclosed JSX tag (it fails the
            # docs-site build). Emit the self-closing form, which is valid MDX and
            # still renders as a line break in a GFM table cell.
            row.append("<br/>".join(sorted({result_label(cell) for cell in matching})))
        add("| " + " | ".join(row) + " |")
    add("")
    add(
        "`—` means the client is not declared on that caller path. A cell label is a result, not a"
        " count: several feature cells can share a client and path."
    )
    add("")

    add("## Cells")
    add("")
    add("| Cell | Client | Caller → upstream | Features | Depths | Result | Evidence |")
    add("| --- | --- | --- | --- | --- | --- | --- |")
    for cell in cells:
        client = clients[cell["client"]]
        depths = ", ".join(str(depth) for depth in cell.get("depths") or []) or "—"
        add(
            f"| `{cell['id']}` | {client['name']} {client['version']} |"
            f" {cell['surface']} → {cell['upstream']} | {', '.join(cell['features'])} | {depths} |"
            f" {result_label(cell)} | {evidence_text(cell)} |"
        )
    add("")

    if matrix.get("router_cells"):
        add("## Router-level cells")
        add("")
        add("| Cell | Area | Features | Result | Evidence |")
        add("| --- | --- | --- | --- | --- |")
        for cell in matrix["router_cells"]:
            add(
                f"| `{cell['id']}` | {cell['area']} | {', '.join(cell.get('features') or [])} |"
                f" {result_label(cell)} | {evidence_text(cell)} |"
            )
        add("")

    failing = [cell for cell in cells if cell["status"] == "fail"]
    if failing:
        add("## Failing cells")
        add("")
        add("| Cell | Client | Features | Issue | Observed |")
        add("| --- | --- | --- | --- | --- |")
        for cell in failing:
            issue = cell.get("issue")
            issue_text = f"[#{issue}](https://github.com/metrum-ai/router/issues/{issue})" if issue else "untriaged"
            add(
                f"| `{cell['id']}` | {clients[cell['client']]['name']} | {', '.join(cell['features'])} |"
                f" {issue_text} | {cell.get('note') or '—'} |"
            )
        add("")

    live = [cell for cell in cells if cell.get("live")]
    if live:
        add("## Live results")
        add("")
        add("| Cell | Date | Commit | Result | Cost | Cost source |")
        add("| --- | --- | --- | --- | --- | --- |")
        for cell in live:
            block = cell["live"]
            cost = block["cost"]
            scope = " (run total)" if cost.get("scope") == "run" else ""
            add(
                f"| `{cell['id']}` | {block['date']} | `{block['commit'][:12]}` | {cell['status']} |"
                f" {usd_text(cost)} | {cost['source']}{scope} |"
            )
        add("")
        add(
            "Cost sources: `usage_rows` is the router's own `request_usage` for routed cells;"
            " `provider_invoiced` is billed by the provider outside the router and is not in those rows;"
            " `estimate` is list-rate arithmetic with the invoice pending; `not_recorded` means the"
            " evidence carries no cost and none is claimed."
        )
        add("")

    not_covered = [cell for cell in cells if cell["status"] == "not-covered"]
    if not_covered:
        add("## Not covered")
        add("")
        add("| Cell | Client | Features | Why not |")
        add("| --- | --- | --- | --- |")
        for cell in not_covered:
            add(
                f"| `{cell['id']}` | {clients[cell['client']]['name']} | {', '.join(cell['features'])} |"
                f" {cell['reason']} |"
            )
        add("")

    unsupported = [cell for cell in cells if cell["status"] == "unsupported"]
    if unsupported:
        add("## Unsupported by contract")
        add("")
        add("| Cell | Client | Features | Declared by |")
        add("| --- | --- | --- | --- |")
        for cell in unsupported:
            doc = cell["doc"]
            label = doc.split("#")[-1].replace("-", " ") if "#" in doc else doc
            add(
                f"| `{cell['id']}` | {clients[cell['client']]['name']} | {', '.join(cell['features'])} |"
                f" {doc_link(doc, label)} |"
            )
        add("")

    add("## Rerun")
    add("")
    add("Mock, unit and path cells:")
    add("")
