def check_page(matrix: dict) -> list[str]:
    if not PAGE_PATH.exists():
        return [f"generated page is missing: {PAGE_PATH.relative_to(ROOT)}"]
    if PAGE_PATH.read_text(encoding="utf-8") != render(matrix):
        return [
            "generated page is out of date with tests/tool_compat/matrix.json;"
            " run `python3 scripts/tool_compat_matrix.py --write`"
        ]
    return []


def write_page(matrix: dict) -> None:
    PAGE_PATH.parent.mkdir(parents=True, exist_ok=True)
    PAGE_PATH.write_text(render(matrix), encoding="utf-8")


def ingest(matrix: dict, report: dict) -> tuple[dict, list[str]]:
    errors: list[str] = []
    if report.get("schema_version") != 1:
        errors.append("report schema_version must be 1")
    runner = report.get("runner")
    if runner not in REPORT_RUNNERS:
        errors.append(f"report runner must be one of {sorted(REPORT_RUNNERS)}")
    date = report.get("date")
    if not isinstance(date, str) or not re.fullmatch(r"\d{4}-\d{2}-\d{2}", date):
        errors.append("report date must be YYYY-MM-DD")
    commit = report.get("commit")
    if not isinstance(commit, str) or not re.fullmatch(r"[0-9a-f]{7,40}", commit):
        errors.append("report commit must be a hex commit")
    cost = report.get("cost")
    errors.extend(validate_cost("report", False, cost) if cost is not None else [])
    results = report.get("cells")
    if not isinstance(results, list) or not results:
        errors.append("report cells must be a non-empty list")
        return matrix, errors
    known = {cell["id"]: cell for cell in matrix["cells"]}
    applied = 0
    for result in results:
        cell_id = result.get("id")
        status = result.get("status")
        if cell_id not in known:
            errors.append(f"report names unknown cell {cell_id!r}")
            continue
        if status not in {"pass", "fail"}:
            errors.append(f"{cell_id}: report status must be pass or fail")
            continue
        cell = known[cell_id]
        cell["status"] = status
        if status == "pass":
            cell["tier"] = "live"
        live = {
            "date": date,
            "commit": commit,
            "runner": runner,
            "cost": cost or {"usd": None, "source": "not_recorded", "scope": "run"},
            "detail": result.get("detail", ""),
        }
        if status == "fail":
            live["triage_required"] = not isinstance(result.get("issue"), int)
            if isinstance(result.get("issue"), int):
                cell["issue"] = result["issue"]
            else:
                cell.pop("issue", None)
                cell["note"] = result.get("detail") or "live run failure; triage issue required"
        cell["live"] = live
        applied += 1
    errors.extend(validate(matrix, allow_untriaged=True))
    if errors:
        return matrix, errors
    matrix["updated"] = date
    print(f"ingested {applied} cell result(s) from {runner} at {commit}", file=sys.stderr)
    return matrix, []


def compare(baseline: dict, current: dict) -> list[str]:
    errors: list[str] = []
    base = {cell["id"]: cell for cell in baseline.get("cells") or []}
    now = {cell["id"]: cell for cell in current.get("cells") or []}
    for cell_id, before in base.items():
        after = now.get(cell_id)
        if after is None:
            errors.append(f"{cell_id}: cell disappeared from the matrix")
            continue
        if before.get("status") == "pass" and after.get("status") != "pass":
            errors.append(f"{cell_id}: regressed pass -> {after.get('status')}")
        if before.get("tier") == "live" and after.get("tier") != "live":
            errors.append(f"{cell_id}: live evidence downgraded to {after.get('tier')}")
    for cell_id in now:
        if cell_id not in base:
            print(f"new cell: {cell_id}", file=sys.stderr)
    return errors


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="validate the matrix and the generated page")
    parser.add_argument(
        "--allow-untriaged",
        action="store_true",
        help="allow recorded live failures that do not have an issue yet",
    )
    parser.add_argument("--write", action="store_true", help="regenerate the page from the matrix")
    parser.add_argument("--ingest", type=Path, help="JSON live-run report to record into the matrix")
    parser.add_argument("--compare", type=Path, help="baseline matrix to detect regressions")
    parser.add_argument("--matrix", type=Path, default=MATRIX_PATH)
    args = parser.parse_args()

    try:
        matrix = load(args.matrix)
    except (OSError, json.JSONDecodeError, MatrixError) as exc:
        print(f"cannot read matrix: {exc}", file=sys.stderr)
        return 2
    errors = validate(matrix, allow_untriaged=args.allow_untriaged)
    if errors:
        for error in errors:
            print(error, file=sys.stderr)
        return 1

    if args.compare:
        try:
            baseline = load(args.compare)
        except (OSError, json.JSONDecodeError) as exc:
            print(f"cannot read baseline: {exc}", file=sys.stderr)
            return 2
        errors = compare(baseline, matrix)
        for error in errors:
            print(error, file=sys.stderr)
        if errors:
            return 1

    if args.ingest:
        try:
            report = json.loads(args.ingest.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            print(f"cannot read report: {exc}", file=sys.stderr)
            return 2
        matrix, errors = ingest(matrix, report)
        for error in errors:
            print(error, file=sys.stderr)
        if errors:
            return 1
        if args.write:
            args.matrix.write_text(json.dumps(matrix, indent=2) + "\n", encoding="utf-8")
            write_page(matrix)
            print(f"wrote {args.matrix.relative_to(ROOT)} and {PAGE_PATH.relative_to(ROOT)}")
        else:
            print(json.dumps(matrix, indent=2))
        return 0

    if args.write:
        write_page(matrix)
        print(f"wrote {PAGE_PATH.relative_to(ROOT)}")
    if args.check or not args.write:
        errors = check_page(matrix)
        for error in errors:
            print(error, file=sys.stderr)
        if errors:
            return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
